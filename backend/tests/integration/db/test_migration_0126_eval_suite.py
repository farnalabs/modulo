"""Integration test for migration 0126_eval_suite_entity (FAR-374 Phase 1).

Runs the real Alembic ``upgrade``/``downgrade`` of revision 0126 against a live
Postgres (testcontainers) and verifies:

  * the ``eval_suites`` table is created with RLS enabled + FORCEd and the
    ``rls_org_isolation`` org-isolation policy;
  * the backfill creates one EvalSuite per DISTINCT (organisation_id, suite_id)
    plus a per-org sentinel for NULL suite_id, and links eval_definitions via
    ``eval_suite_id``;
  * the backfill is idempotent (re-running it produces no duplicate suites);
  * cross-org RLS on eval_suites actually filters rows for a non-superuser role;
  * the downgrade drops the policy, the FK column, and the table cleanly, and a
    re-upgrade restores a clean (empty) head state.

The test resets ``alembic_version`` to the revision *before* 0130, seeds data,
and re-runs 0130 so the real backfill executes against live Postgres. It
restores the head state in ``finally`` so the shared session schema is
undisturbed for later tests.
"""

import os
import types
import uuid
from collections.abc import AsyncIterator
from pathlib import Path

import pytest
import pytest_asyncio
from alembic import command
from alembic.config import Config
from sqlalchemy import text
from sqlalchemy.ext.asyncio import create_async_engine
from sqlalchemy.pool import NullPool

pytestmark = [pytest.mark.integration]
# test-only role names are generated by this test (not caller input); they are
# SQL identifiers and cannot be passed as bind parameters, so S608 is waived.

BACKEND_ROOT = Path(__file__).parents[3]  # backend/

MIGRATION_REV = "0130_eval_suite_entity"
# Reset only to the revision immediately before 0130. The 0126-0129 migrations on
# origin/main are applied by the session's migrated_db_url fixture and are NOT all
# idempotent (some DROP constraints without IF EXISTS), so re-running the whole
# chain would fail. Resetting to 0129 re-runs only our idempotent 0130 migration.
PREV_REV = "0129_runs_json_to_jsonb"

# Mirror of the backfill DO block used by the migration, exposed so we can run
# it a SECOND time and prove idempotency (no duplicate EvalSuite rows).
_BACKFILL_SQL = """
DO $$
DECLARE
    org_rec RECORD;
    suite_rec RECORD;
    new_suite_id UUID;
BEGIN
    FOR org_rec IN SELECT DISTINCT organisation_id FROM eval_definitions LOOP
        FOR suite_rec IN
            SELECT organisation_id, suite_id
            FROM eval_definitions
            WHERE organisation_id = org_rec.organisation_id
              AND suite_id IS NOT NULL
            GROUP BY organisation_id, suite_id
        LOOP
            INSERT INTO eval_suites (
                id, organisation_id, owner_team_id, visibility, name, description,
                legacy_suite_id, eval_definition_ids, input_set_ref, created_at, updated_at
            )
            SELECT gen_random_uuid(), suite_rec.organisation_id, NULL, 'org',
                   left(suite_rec.suite_id, 255),
                   'Backfilled from legacy eval_definitions.suite_id (FAR-374).',
                   suite_rec.suite_id,
                   COALESCE((SELECT json_agg(ed.id ORDER BY ed.id)
                             FROM eval_definitions ed
                             WHERE ed.organisation_id = suite_rec.organisation_id
                               AND ed.suite_id = suite_rec.suite_id
                               AND ed.deleted_at IS NULL), '[]'::json),
                   NULL, now(), now()
            WHERE NOT EXISTS (SELECT 1 FROM eval_suites s
                              WHERE s.organisation_id = suite_rec.organisation_id
                                AND s.legacy_suite_id = suite_rec.suite_id)
            RETURNING id INTO new_suite_id;
            UPDATE eval_definitions SET eval_suite_id = new_suite_id
            WHERE organisation_id = suite_rec.organisation_id
              AND suite_id = suite_rec.suite_id
              AND eval_suite_id IS NULL;
        END LOOP;
        INSERT INTO eval_suites (
            id, organisation_id, owner_team_id, visibility, name, description,
            legacy_suite_id, eval_definition_ids, input_set_ref, created_at, updated_at
        )
        SELECT gen_random_uuid(), org_rec.organisation_id, NULL, 'org',
               '__NO_SUITE__', 'Eval definitions with no legacy suite_id (FAR-374).',
               '__NO_SUITE__',
               COALESCE((SELECT json_agg(ed.id ORDER BY ed.id)
                         FROM eval_definitions ed
                         WHERE ed.organisation_id = org_rec.organisation_id
                           AND ed.suite_id IS NULL AND ed.deleted_at IS NULL), '[]'::json),
               NULL, now(), now()
        WHERE EXISTS (SELECT 1 FROM eval_definitions ed
                      WHERE ed.organisation_id = org_rec.organisation_id
                        AND ed.suite_id IS NULL)
          AND NOT EXISTS (SELECT 1 FROM eval_suites s
                          WHERE s.organisation_id = org_rec.organisation_id
                            AND s.legacy_suite_id = '__NO_SUITE__')
        RETURNING id INTO new_suite_id;
        UPDATE eval_definitions SET eval_suite_id = new_suite_id
        WHERE organisation_id = org_rec.organisation_id
          AND suite_id IS NULL AND eval_suite_id IS NULL;
    END LOOP;
END $$;
"""


def _alembic_config(db_url: str) -> Config:
    config = Config(BACKEND_ROOT / "alembic.ini")
    config.set_main_option("sqlalchemy.url", db_url)
    config.set_main_option(
        "script_location",
        str(BACKEND_ROOT / "src" / "modulo" / "db" / "migrations"),
    )
    config.config_file_name = None
    return config


def _swap_db_name(db_url: str, new_db: str) -> str:
    """Return ``db_url`` with its database name replaced by ``new_db``."""
    from urllib.parse import urlparse, urlunparse

    parsed = urlparse(db_url)
    return urlunparse(parsed._replace(path=f"/{new_db}"))


@pytest_asyncio.fixture
async def isolated_db_url(db_url: str, monkeypatch: pytest.MonkeyPatch) -> AsyncIterator[str]:
    """A fresh, private Postgres database migrated only up to ``PREV_REV``.

    ``test_0126`` downgrades the schema (dropping ``eval_suites`` /
    ``eval_suite_id``) and re-upgrades it. Running that against the shared
    session ``migrated_db_url`` corrupts the one database every other
    integration test uses, cascading into spurious ``eval_suite_id does not
    exist`` failures across the suite. Give this test its own database so the
    shared schema is never touched.

    The isolated database is provisioned from ``template0`` (guaranteed empty)
    rather than the default ``template1``. ``migrations/env.py`` overrides the
    alembic ``sqlalchemy.url`` with ``DATABASE_URL``/``DATABASE_ADMIN_URL`` from
    the environment, so we point those vars at the isolated database here —
    otherwise ``command.upgrade`` would run against the shared session database
    and the migrations that create tables such as ``library_sync_state`` would
    collide with the already-applied schema (DuplicateTable).
    """
    admin_engine = create_async_engine(db_url, poolclass=NullPool, execution_options={"isolation_level": "AUTOCOMMIT"})
    db_name = f"eval_suite_iso_{uuid.uuid4().hex[:10]}"
    async with admin_engine.connect() as conn:
        # template0 is always present and empty, so the new database starts
        # with no inherited tables regardless of template1's state.
        await conn.execute(text(f'CREATE DATABASE "{db_name}" WITH TEMPLATE template0'))
    await admin_engine.dispose()

    iso_url = _swap_db_name(db_url, db_name)
    # Ensure env.py's DATABASE_URL / DATABASE_ADMIN_URL override resolves to this
    # isolated database, not the shared session database.
    monkeypatch.setenv("DATABASE_URL", iso_url)
    monkeypatch.setenv("DATABASE_ADMIN_URL", iso_url)
    eng = create_async_engine(iso_url, poolclass=NullPool)
    async with eng.connect() as conn:
        await conn.execute(
            text("CREATE TABLE IF NOT EXISTS alembic_version (version_num VARCHAR(255) NOT NULL PRIMARY KEY)")
        )
        await conn.commit()
    await eng.dispose()

    # ``env.py`` overrides the connection URL with ``DATABASE_URL`` (or
    # ``DATABASE_ADMIN_URL``), so the ``sqlalchemy.url`` set inside
    # ``_alembic_config`` is ignored. Point ``DATABASE_URL`` at the isolated
    # database here; otherwise the upgrade runs against the shared session DB.
    # The shared DB is left at a mid-chain version by other migration tests
    # (e.g. ``test_migration_0120_org_fk`` resets it to 0119 and only restores
    # it to 0120), so re-running the 0120->0129 span there collides on
    # already-existing tables such as ``library_sync_state`` (migration 0122),
    # surfacing as ``relation "library_sync_state" already exists``. Restoring
    # the previous value keeps the shared session env untouched for other tests.
    prev_db_url = os.environ.get("DATABASE_URL")
    monkeypatch.setenv("DATABASE_URL", iso_url)
    try:
        command.upgrade(_alembic_config(iso_url), PREV_REV)
    finally:
        if prev_db_url is None:
            monkeypatch.delenv("DATABASE_URL", raising=False)
        else:
            monkeypatch.setenv("DATABASE_URL", prev_db_url)

    try:
        yield iso_url
    finally:
        admin_engine = create_async_engine(
            db_url, poolclass=NullPool, execution_options={"isolation_level": "AUTOCOMMIT"}
        )
        async with admin_engine.connect() as conn:
            await conn.execute(
                text(
                    "SELECT pg_terminate_backend(pid) FROM pg_stat_activity "
                    "WHERE datname = :n AND pid <> pg_backend_pid()"
                ).bindparams(n=db_name)
            )
            await conn.execute(text(f'DROP DATABASE IF EXISTS "{db_name}"'))
        await admin_engine.dispose()


async def _seed(db_url: str, orgs: tuple[uuid.UUID, uuid.UUID]) -> dict[str, uuid.UUID]:
    """Seed two orgs each with a pipeline + account and eval_definitions."""
    org_a, org_b = orgs
    engine = create_async_engine(db_url, poolclass=NullPool)
    defs: dict[str, uuid.UUID] = {}
    try:
        async with engine.begin() as conn:
            for oid, slug in [(org_a, "eval-org-a"), (org_b, "eval-org-b")]:
                await conn.execute(
                    text("INSERT INTO organisations (id, name, slug, settings_json) VALUES (:id, :n, :s, '{}'::json)"),
                    {"id": str(oid), "n": slug, "s": slug},
                )
                await conn.execute(
                    text(
                        "INSERT INTO accounts (id, email, display_name, password_hash, "
                        "auth_provider, active) VALUES (:id, :e, :n, 'hash', 'local', true)"
                    ),
                    {"id": str(uuid.uuid4()), "e": f"{slug}@example.com", "n": slug},
                )
            for oid, slug in [(org_a, "eval-org-a"), (org_b, "eval-org-b")]:
                await conn.execute(
                    text(
                        "INSERT INTO pipelines (id, organisation_id, name, account_id, "
                        "max_concurrent_runs, lock_wait_timeout_seconds, node_timeout_seconds, "
                        "run_context_defaults, graph_nodes_json) "
                        "VALUES (:id, :oid, :name, (SELECT id FROM accounts WHERE email = :e), "
                        "10, 30, 300, '{}'::json, '[]'::json)"
                    ),
                    {"id": str(uuid.uuid4()), "oid": str(oid), "name": f"{slug}-pipeline", "e": f"{slug}@example.com"},
                )

            acc_a = (await conn.execute(text("SELECT id FROM accounts WHERE email='eval-org-a@example.com'"))).scalar()
            pipe_a = (await conn.execute(text("SELECT id FROM pipelines WHERE name='eval-org-a-pipeline'"))).scalar()
            for name, suite in [
                ("a1", "suiteA"),
                ("a2", "suiteA"),
                ("b1", "suiteB"),
                ("n1", None),
            ]:
                did = uuid.uuid4()
                defs[name] = did
                await conn.execute(
                    text(
                        "INSERT INTO eval_definitions "
                        "(id, organisation_id, pipeline_id, account_id, name, eval_type, "
                        "config_json, failure_behaviour, suite_id) "
                        "VALUES (:id, :oid, :pid, :aid, :name, 'regex', '{}'::json, 'warn', :suite)"
                    ),
                    {
                        "id": str(did),
                        "oid": str(org_a),
                        "pid": str(pipe_a),
                        "aid": str(acc_a),
                        "name": name,
                        "suite": suite,
                    },
                )

            acc_b = (await conn.execute(text("SELECT id FROM accounts WHERE email='eval-org-b@example.com'"))).scalar()
            pipe_b = (await conn.execute(text("SELECT id FROM pipelines WHERE name='eval-org-b-pipeline'"))).scalar()
            did = uuid.uuid4()
            defs["b_org_suiteA"] = did
            await conn.execute(
                text(
                    "INSERT INTO eval_definitions "
                    "(id, organisation_id, pipeline_id, account_id, name, eval_type, "
                    "config_json, failure_behaviour, suite_id) "
                    "VALUES (:id, :oid, :pid, :aid, :name, 'regex', '{}'::json, 'warn', 'suiteA')"
                ),
                {
                    "id": str(did),
                    "oid": str(org_b),
                    "pid": str(pipe_b),
                    "aid": str(acc_b),
                    "name": "b_org_suiteA",
                },
            )
    finally:
        await engine.dispose()
    return defs


async def _count_suites(engine, org: uuid.UUID | None = None) -> int:
    async with engine.connect() as conn:
        if org is None:
            n = (await conn.execute(text("SELECT count(*) FROM eval_suites"))).scalar()
        else:
            n = (
                await conn.execute(
                    text("SELECT count(*) FROM eval_suites WHERE organisation_id = :o"),
                    {"o": str(org)},
                )
            ).scalar()
    return int(n)


async def test_0126_eval_suite_backfill_rls_and_downgrade(isolated_db_url, monkeypatch) -> None:
    db_url = isolated_db_url
    monkeypatch.setenv("DATABASE_URL", db_url)
    config = _alembic_config(db_url)
    engine = create_async_engine(db_url, poolclass=NullPool)

    org_a = uuid.uuid4()
    org_b = uuid.uuid4()

    try:
        # Reset to the revision before 0130 (only 0130 is re-run, which is
        # idempotent), then seed data (so the backfill has something to migrate).
        # The shared session schema is restored in finally.
        async with engine.begin() as conn:
            await conn.execute(
                text("UPDATE alembic_version SET version_num = :rev"),
                {"rev": PREV_REV},
            )

        await _seed(db_url, (org_a, org_b))

        # Run the real migration (backfill executes here).
        command.upgrade(config, MIGRATION_REV)

        # --- Backfill assertions ---
        # Org A: suiteA, suiteB, sentinel => 3 suites.
        assert await _count_suites(engine, org_a) == 3, "org A should have 3 suites"
        # Org B has only a "suiteA" def (no NULL-suite_id def) so it gets exactly
        # 1 suite (no sentinel — the sentinel is only created for orgs that have
        # at least one NULL legacy suite_id to bucket).
        assert await _count_suites(engine, org_b) == 1, "org B should have 1 suite"

        async with engine.connect() as conn:
            linked = (
                await conn.execute(
                    text("SELECT count(*) FROM eval_definitions WHERE organisation_id = :o AND eval_suite_id IS NULL"),
                    {"o": str(org_a)},
                )
            ).scalar()
            assert linked == 0, "all org A eval_definitions should be backfilled"

            member_count = (
                await conn.execute(
                    text(
                        "SELECT jsonb_array_length(eval_definition_ids) "
                        "FROM eval_suites WHERE organisation_id = :o AND legacy_suite_id = 'suiteA'"
                    ),
                    {"o": str(org_a)},
                )
            ).scalar()
            assert member_count == 2, "org A suiteA should list 2 member defs"

            sentinel = (
                await conn.execute(
                    text(
                        "SELECT count(*) FROM eval_suites "
                        "WHERE organisation_id = :o AND legacy_suite_id = '__NO_SUITE__'"
                    ),
                    {"o": str(org_a)},
                )
            ).scalar()
            assert sentinel == 1, "org A should have exactly one sentinel suite"

        # --- Idempotency: running the backfill a second time adds no rows ---
        async with engine.begin() as conn:
            await conn.execute(text(_BACKFILL_SQL))
        assert await _count_suites(engine, org_a) == 3, "backfill must be idempotent (no dup suites)"
        assert await _count_suites(engine, org_b) == 1, "backfill must be idempotent (no dup suites)"

        # --- RLS assertions ---
        async with engine.connect() as conn:
            row = (
                await conn.execute(
                    text("SELECT relrowsecurity, relforcerowsecurity FROM pg_class WHERE relname = 'eval_suites'")
                )
            ).fetchone()
            assert row is not None, "eval_suites should exist"
            assert row[0] is True, "RLS must be ENABLED on eval_suites"
            assert row[1] is True, "RLS must be FORCED on eval_suites"

            policy = (
                await conn.execute(
                    text(
                        "SELECT count(*) FROM pg_policies "
                        "WHERE tablename = 'eval_suites' AND policyname = 'rls_org_isolation'"
                    )
                )
            ).scalar()
            assert policy == 1, "eval_suites must carry rls_org_isolation policy"

        # --- Cross-org RLS enforcement (non-superuser role) ---
        role = f"test_eval_suite_rls_{uuid.uuid4().hex[:8]}"
        async with engine.connect() as conn:
            await conn.execute(text(f'CREATE ROLE "{role}" NOSUPERUSER NOBYPASSRLS NOLOGIN'))
            await conn.execute(text(f'GRANT USAGE ON SCHEMA public TO "{role}"'))
            await conn.execute(text(f'GRANT SELECT, INSERT ON eval_suites TO "{role}"'))
            await conn.execute(text(f'GRANT SELECT ON organisations TO "{role}"'))
            await conn.execute(text("COMMIT"))

        try:
            suite_a = uuid.uuid4()
            suite_b = uuid.uuid4()
            async with engine.begin() as conn:
                await conn.execute(
                    text(
                        "INSERT INTO eval_suites (id, organisation_id, visibility, name) "
                        "VALUES (:id, :o, 'org', 'RLS-A')"
                    ),
                    {"id": str(suite_a), "o": str(org_a)},
                )
                await conn.execute(
                    text(
                        "INSERT INTO eval_suites (id, organisation_id, visibility, name) "
                        "VALUES (:id, :o, 'org', 'RLS-B')"
                    ),
                    {"id": str(suite_b), "o": str(org_b)},
                )

            async with engine.connect() as conn:
                async with conn.begin():
                    await conn.execute(text(f'SET LOCAL ROLE "{role}"'))
                    await conn.execute(
                        text("SELECT set_config('app.organisation_id', :o, true)"),
                        {"o": str(org_a)},
                    )
                    rows = (
                        await conn.execute(
                            text("SELECT id::text FROM eval_suites WHERE id = ANY(:ids)"),
                            {"ids": [str(suite_a), str(suite_b)]},
                        )
                    ).fetchall()
                    visible = {r[0] for r in rows}
                assert visible == {str(suite_a)}, f"org A should see only its suite; got {visible}"

            async with engine.connect() as conn:
                async with conn.begin():
                    await conn.execute(text(f'SET LOCAL ROLE "{role}"'))
                    await conn.execute(
                        text("SELECT set_config('app.organisation_id', :o, true)"),
                        {"o": str(org_b)},
                    )
                    rows = (
                        await conn.execute(
                            text("SELECT id::text FROM eval_suites WHERE id = ANY(:ids)"),
                            {"ids": [str(suite_a), str(suite_b)]},
                        )
                    ).fetchall()
                    visible = {r[0] for r in rows}
                assert visible == {str(suite_b)}, f"org B should see only its suite; got {visible}"
        finally:
            async with engine.connect() as conn:
                await conn.execute(text(f'DROP OWNED BY "{role}"'))
                await conn.execute(text(f'DROP ROLE IF EXISTS "{role}"'))
                await conn.execute(text("COMMIT"))

            # --- Downgrade reverses the migration cleanly (-1 = one step back) ---
            # env.py's boot fast-path skips migrations when invoked programmatically
            # (config.cmd_opts is None -> _invocation_is_upgrade() wrongly True, and
            # the DB is at head). Force the downgrade direction so it actually runs.
            config.cmd_opts = types.SimpleNamespace(command="downgrade")
            command.downgrade(config, "-1")
            async with engine.connect() as conn:
                exists = (
                    await conn.execute(
                        text("SELECT count(*) FROM information_schema.tables WHERE table_name = 'eval_suites'")
                    )
                ).scalar()
                assert exists == 0, "eval_suites should be dropped after downgrade"
                col = (
                    await conn.execute(
                        text(
                            "SELECT count(*) FROM information_schema.columns "
                            "WHERE table_name = 'eval_definitions' AND column_name = 'eval_suite_id'"
                        )
                    )
                ).scalar()
                assert col == 0, "eval_suite_id column should be dropped after downgrade"
    finally:
        # Restore the head state: drop seeded data, re-run migration to head.
        async with engine.begin() as conn:
            await conn.execute(
                text("DELETE FROM eval_definitions WHERE organisation_id IN (:a, :b)"),
                {"a": str(org_a), "b": str(org_b)},
            )
            await conn.execute(
                text("DELETE FROM pipelines WHERE organisation_id IN (:a, :b)"),
                {"a": str(org_a), "b": str(org_b)},
            )
            await conn.execute(text("DELETE FROM accounts WHERE email LIKE 'eval-org-%@example.com'"))
            await conn.execute(
                text("DELETE FROM organisations WHERE id IN (:a, :b)"),
                {"a": str(org_a), "b": str(org_b)},
            )
        config.cmd_opts = types.SimpleNamespace(command="upgrade")
        command.upgrade(config, "heads")
        await engine.dispose()
